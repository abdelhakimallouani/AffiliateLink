
CREATE TABLE offer_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    advertiser_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    landing_url VARCHAR(500) NOT NULL,
    niche VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE offer_campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(150) NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    budget NUMERIC(12, 2) NOT NULL,
    payout_model VARCHAR(30) NOT NULL,
    payout_value NUMERIC(12, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    offer_id BIGINT NOT NULL,

    CONSTRAINT fk_offer_campaigns_offer
        FOREIGN KEY (offer_id)
        REFERENCES offers(id)
);

CREATE TABLE offer_offer_tags (
    offer_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    PRIMARY KEY (offer_id, tag_id),

    CONSTRAINT fk_offer_offer_tags_offer
        FOREIGN KEY (offer_id)
        REFERENCES offers(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_offer_offer_tags_tag
        FOREIGN KEY (tag_id)
        REFERENCES offer_tags(id)
        ON DELETE CASCADE
);